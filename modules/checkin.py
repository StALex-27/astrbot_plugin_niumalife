def get_checkin_grade(luck_value: int) -> tuple[dict, str]:
    """根据幸运值获取新版品级和签文。返回 (grade_info, fortune_text)。"""
    # 先检查锚点
    if luck_value in GRADE_RATINGS:
        grade = GRADE_RATINGS[luck_value]
    else:
        # 查找范围
        grade = None
        for (low, high), g in GRADE_RATINGS.items():
            if isinstance(low, int) and isinstance(high, int) and low <= luck_value <= high:
                grade = g
                break
        if grade is None:
            grade = GRADE_RATINGS[(11, 30)]  # 默认降级

    grade_type = grade["type"]
    pool = FORTUNE_POOL.get(grade_type, FORTUNE_POOL.get("warm", ["今天也是平凡又幸运的一天喵~"]))
    fortune = random.choice(pool)
    return grade, fortune


